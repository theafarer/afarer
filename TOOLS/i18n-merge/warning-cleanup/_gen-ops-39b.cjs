// _gen-ops-39b.cjs — shard 39 extension (dist-walk findings), APPENDS ops to _ops-data-39.cjs
// Run ONCE against pre-39b state. New families:
//   - de/tourism-recreation ISO-strip scar "großen,  & CE-" -> "großen, ISO- und CE-"
//   - ko pages m2 normalization: 12,000㎡ / 12,000m² -> 12,000 m² (site precedent x18)
//   - UI dict src/data/site/i18n-config.json: 12,000m² -> 12,000 m² (ja x5 + ko x5)
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve('.');
const OPS39 = path.join(ROOT, 'TOOLS/i18n-merge/warning-cleanup/_ops-data-39.cjs');
const rd = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const must = (m, w) => {
  if (!m) throw new Error('39b: ' + w);
  return m;
};

const NEW = [];
const OP = (f, find, rep, n) => {
  const t = rd(f);
  const fc = t.split(find).length - 1;
  if (fc !== (n || 1))
    throw new Error(
      '39b find x' + fc + ' expect ' + (n || 1) + ' in ' + f + ' :: ' + JSON.stringify(find.slice(0, 60))
    );
  NEW.push(n ? { f, find, rep, n } : { f, find, rep });
};

// --- 1. de/tourism-recreation ISO-strip scar ---
OP(
  'src/data/pages/de/tourism-recreation.yaml',
  '12.000 m\u00b2 gro\u00dfen,  & CE-zertifizierten',
  '12.000 m\u00b2 gro\u00dfen, ISO- und CE-zertifizierten'
);

// --- 2. ko pages m2 normalization ---
const KO = [
  ['afarer-story.yaml', '\u33a1', 1], // 12,000㎡
  ['brand-marine-expertise.yaml', 'm\u00b2', 1],
  ['brand-team.yaml', 'm\u00b2', 1],
  ['brand-why-afarer.yaml', 'm\u00b2', 1],
  ['certifications.yaml', 'm\u00b2', 1],
  ['custom.yaml', '\u33a1', 1],
  ['factory-capacity.yaml', '\u33a1', 2],
  ['factory-capacity.yaml', 'm\u00b2', 1],
  ['factory.yaml', '\u33a1', 1],
  ['factory.yaml', 'm\u00b2', 1],
  ['media.yaml', 'm\u00b2', 1],
  ['tourism-recreation.yaml', 'm\u00b2', 1],
  ['trust.yaml', 'm\u00b2', 1],
];
for (const [file, glyph, n] of KO) {
  OP('src/data/pages/ko/' + file, '12,000' + glyph, '12,000 m\u00b2', n);
}

// --- 3. UI dict ---
OP('src/data/site/i18n-config.json', '12,000m\u00b2', '12,000 m\u00b2', 10);

// --- sanity: no other bad variants in ko pages / UI dict ---
for (const file of [
  'afarer-story.yaml',
  'brand-marine-expertise.yaml',
  'brand-team.yaml',
  'brand-why-afarer.yaml',
  'certifications.yaml',
  'custom.yaml',
  'factory-capacity.yaml',
  'factory.yaml',
  'media.yaml',
  'tourism-recreation.yaml',
  'trust.yaml',
]) {
  const t = rd('src/data/pages/ko/' + file);
  const bad = t.match(/12[,.]000(?:\u33a1|m\u00b2)/gu) || []; // no-space forms only
  for (const b of bad) {
    if (b !== '12,000\u33a1' && b !== '12,000m\u00b2')
      throw new Error('39b unexpected ko variant ' + JSON.stringify(b) + ' in ' + file);
  }
}
{
  const t = rd('src/data/site/i18n-config.json');
  for (const m of t.match(/12[,.]000(?:\u33a1|m\u00b2)/gu) || []) {
    if (m !== '12,000m\u00b2') throw new Error('39b unexpected UI variant ' + JSON.stringify(m));
  }
}

// --- append to shard 39 static module ---
const ops = require(OPS39);
if (ops.length !== 91) throw new Error('39b base ops=' + ops.length);
const all = ops.concat(NEW);
fs.writeFileSync(
  OPS39,
  '// shard 39 (GENERATED by _gen-ops-39.cjs + _gen-ops-39b.cjs — do not edit by hand)\n' +
    '// 106 ops: custom MOQ 50 x21 (20 locale L56 + fr L3), resorts roi "+" x7, equipment items[3] x11,\n' +
    '// ja m2-family x10, ja factory-process steps x6 blocks, traceability " + " x7, tr serigrafi x1,\n' +
    '// ISO-strip x15 (EN root + 9 cwb + 5 tourism incl. de 39b), fi EN-residue x14 (hydro 11 + thickness 3),\n' +
    '// 39b: ko pages m2 x13 + UI dict i18n-config.json m2 x10 (n:10)\n' +
    'module.exports = ' +
    JSON.stringify(all, null, 2) +
    ';\n'
);
console.log('39b appended ' + NEW.length + ' ops, total ' + all.length);
