// shard 47c: post-patch maintenance — rewrite op #0 of _ops-data-47.cjs (run AFTER 47/47b patch + prettier).
// Root cause: prettier re-quotes a single-quoted yaml scalar containing '' escapes into a double-quoted
// scalar with a plain apostrophe. The 47b hand-computed terminal `SUP''er` therefore never existed on disk;
// the real post-prettier terminal L3 is a double-quoted line containing SUP'er. Op #0 kept pointing at the
// single-quote terminal, so the engine reported it as "applies" and a real --patch would have injected a
// literal double apostrophe into the double-quoted scalar (corruption).
// Fix: full-line op — find = historical pre-47 single-quoted L3 (replayable from HEAD), rep = actual
// double-quoted terminal L3 (matches disk, idempotent). See TECH.md L37-5.
const fs = require('fs');

const OPS_PATH = 'E:/github/afarer/TOOLS/i18n-merge/warning-cleanup/_ops-data-47.cjs';
const HOME = 'E:/github/afarer/src/data/pages/da/home.yaml';

const OLD_FIND = "performance-oppustelige SUP'er";
const OLD_REP = "performance-oppustelige SUP''er";

const NEW_FIND =
  "  description: 'afarer designer performance-oppustelige SUPer til åbent vand, touring, yoga og eventyr. Drop-stitch-stivhed, tryktestet board for board, med eksklusive landepartnerskaber og begrænsede co-branded kollektioner. Udforsk kollektionen.'";
const NEW_REP =
  '  description: "afarer designer performance-oppustelige SUP\'er til åbent vand, touring, yoga og eventyr. Drop-stitch-stivhed, tryktestet board for board, med eksklusive landepartnerskaber og begrænsede co-branded kollektioner. Udforsk kollektionen."';

// pre-conditions
const home = fs.readFileSync(HOME, 'utf8');
if (home.split(NEW_REP).length - 1 !== 1) {
  throw new Error('home.yaml does not contain the expected post-prettier terminal L3 exactly once');
}
if (home.includes(OLD_REP)) {
  throw new Error('home.yaml unexpectedly contains the 47b single-quote terminal');
}

const ops = require(OPS_PATH);
if (ops[0].find !== OLD_FIND || ops[0].rep !== OLD_REP) {
  throw new Error('op #0 shape mismatch — expected the 47b intermediate op');
}
ops[0] = { f: ops[0].f, find: NEW_FIND, rep: NEW_REP, n: 1 };

// serialize in prettier singleQuote style: prefer '...' unless the string contains '
function q(s) {
  if (!s.includes("'")) return "'" + s + "'";
  return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}
const body = ops
  .map((o) => {
    const n = typeof o.n === 'number' ? `, n: ${o.n}` : '';
    return `  {\n    f: ${q(o.f)},\n    find: ${q(o.find)},\n    rep: ${q(o.rep)}${n},\n  },`;
  })
  .join('\n');
const header = [
  '// shard 47 (GENERATED by _gen-ops-47.cjs — do not edit by hand; maintained by _gen-ops-47b/47c.cjs)',
  '// 58 ops — da page-yaml EN residue (56 fixes + 47b quote split + 47c full-line L3 terminal). See TECH.md L37.',
  '// Fragment ops: find occurs exactly n times in file; pre-patch values asserted by generator.',
].join('\n');
fs.writeFileSync(OPS_PATH, header + '\nmodule.exports = [\n' + body + '\n];\n');

// post-condition: reload and verify
delete require.cache[require.resolve(OPS_PATH)];
const ops2 = require(OPS_PATH);
if (ops2.length !== ops.length || ops2[0].find !== NEW_FIND || ops2[0].rep !== NEW_REP) {
  throw new Error('post-write verification failed');
}
console.log('47c OK: op #0 rewritten to full-line terminal, total ops:', ops2.length);
