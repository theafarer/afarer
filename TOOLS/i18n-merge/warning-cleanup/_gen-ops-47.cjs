// shard 47 generator: da page-yaml EN residue (src/data/pages/da/*.yaml) -> _ops-data-47.cjs
// Run ONLY on pre-patch state. Delete _ops-data-47.cjs before re-running (exists-guard).
// Pattern (shard 45/46): pre-patch value-class assertions lock every target fragment's
// current value, count, and line number before emitting ops — any state drift is fatal.
const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const ROOT = path.join(DIR, '..', '..', '..');
const OUT = path.join(DIR, '_ops-data-47.cjs');

if (fs.existsSync(OUT)) {
  console.error('FATAL: _ops-data-47.cjs exists — delete it before re-running the generator.');
  process.exit(1);
}

const data = require('./_b47-data.cjs');
const ops = [];
const files = new Map();

for (const e of data) {
  if (!files.has(e.f)) files.set(e.f, fs.readFileSync(path.join(ROOT, e.f), 'utf8'));
  const raw = files.get(e.f);
  const lines = raw.split('\n').map((l) => l.replace(/\r$/, ''));
  const lns = e.lns || [e.ln];
  for (const ln of lns) {
    const line = lines[ln - 1];
    if (line === undefined) {
      console.error('FATAL ' + e.f + ' L' + ln + ': line does not exist');
      process.exit(1);
    }
    if (!line.includes(e.core)) {
      console.error(
        'FATAL ' +
          e.f +
          ' L' +
          ln +
          ': pre-patch assertion failed, core not on line:\n    core: ' +
          e.core +
          '\n    line: ' +
          line
      );
      process.exit(1);
    }
  }
  let c = 0;
  let p = 0;
  while ((p = raw.indexOf(e.core, p)) !== -1) {
    c++;
    p += 1;
  }
  if (c !== e.n) {
    console.error('FATAL ' + e.f + ': core count ' + c + ' != expected ' + e.n + ' — core: ' + e.core);
    process.exit(1);
  }
  if (e.rep.includes(e.core)) {
    console.error('FATAL ' + e.f + ': rep contains core (non-idempotent) — core: ' + e.core);
    process.exit(1);
  }
  ops.push({ f: e.f, find: e.core, rep: e.rep, n: e.n });
}

function sq(s) {
  return "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n') + "'";
}

let out = '';
out += '// shard 47 (GENERATED by _gen-ops-47.cjs — do not edit by hand)\n';
out += '// ' + ops.length + ' ops — da page-yaml EN residue (56 fixes / 25 files). See TECH.md L37.\n';
out += '// Fragment ops: find occurs exactly n times in file; pre-patch values asserted by generator.\n';
out += 'module.exports = [\n';
for (const o of ops) {
  out += '  {\n';
  out += '    f: ' + sq(o.f) + ',\n';
  out += '    find: ' + sq(o.find) + ',\n';
  out += '    rep: ' + sq(o.rep) + ',\n';
  out += '    n: ' + o.n + ',\n';
  out += '  },\n';
}
out += '];\n';
fs.writeFileSync(OUT, out, 'utf8');
console.log('OK: wrote ' + ops.length + ' ops across ' + files.size + ' files to _ops-data-47.cjs');
