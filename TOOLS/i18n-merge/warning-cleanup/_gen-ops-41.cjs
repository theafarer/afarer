// shard 41 GENERATOR: da/fi thousands-separator normalization (SEP)
// da: comma-thousands -> dot (12.000); fi: -> space (12 000)
// exclusions: 0,001 decimal comma (legal), rgb()/data:image, hull-engineering
// '18 000 h' (site-uniform across 17 locales + EN, left as-is, documented in TECH.md)
// UI dict: da/fi oem.why.factory.desc SEP, fi people.managementDesc EN-residue
// translation (incl. 12 000). da UI Czech contamination (nafukovac\u00ED ~25x) is
// systemic -> registered as separate shard, NOT fixed here
// Run from repo root: node TOOLS/i18n-merge/warning-cleanup/_gen-ops-41.cjs
const fs = require('fs');
const path = require('path');

const ROOT = 'E:/github/afarer';
const ops = [];

function must(cond, msg) {
  if (!cond) throw new Error('FAIL: ' + msg);
}
function count(txt, s) {
  return txt.split(s).length - 1;
}

const SEP = { da: '.', fi: ' ' };
let yamlOps = 0;

for (const lang of ['da', 'fi']) {
  const dir = path.join(ROOT, 'src/data/pages', lang);
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.yaml'))) {
    const fp = 'src/data/pages/' + lang + '/' + f;
    const txt = fs.readFileSync(path.join(dir, f), 'utf8');
    const lines = txt.split('\n');
    lines.forEach((line, i) => {
      if (!/\d{1,3},\d{3}/.test(line)) return;
      if (/0,001/.test(line)) return;
      if (/rgb\(|data:image/.test(line)) return;
      const rep = line.replace(/\b(\d{1,3}),(\d{3})\b/g, '$1' + SEP[lang] + '$2');
      must(rep !== line, fp + ' L' + (i + 1) + ' unchanged');
      must(!/\d{1,3},\d{3}/.test(rep), fp + ' L' + (i + 1) + ' comma residue');
      must(count(txt, line) === 1, fp + ' L' + (i + 1) + ' line not unique: ' + line.slice(0, 60));
      ops.push({ f: fp, find: line, rep });
      yamlOps++;
    });
  }
}

// UI dict ops (raw text, literal UTF-8 as in file)
const uiPath = 'src/data/site/i18n-config.json';
const uiRaw = fs.readFileSync(path.join(ROOT, uiPath), 'utf8');
const M2 = '\u00B2';

// 1. da oem.why.factory.desc
let find = '"12,000 m' + M2 + ' dedikeret';
must(count(uiRaw, find) === 1, 'da oem find count');
ops.push({ f: uiPath, find, rep: '"12.000 m' + M2 + ' dedikeret' });

// 2. fi oem.why.factory.desc
find = '"12,000 m' + M2 + ' omistettu';
must(count(uiRaw, find) === 1, 'fi oem find count');
ops.push({ f: uiPath, find, rep: '"12 000 m' + M2 + ' omistettu' });

// 3. fi people.managementDesc: EN residue -> Finnish (with 12 000)
// NOTE: identical EN value also exists in el block (registered for UI-dict EN-residue
// shard); single-line find would be ambiguous -> anchor with the 5 following lines
// (el diverges at people.subtitle: Greek vs EN), making the 6-line sequence unique.
const uiLines = uiRaw.split('\n');
const mgmtIdxs = [];
uiLines.forEach((l, i) => {
  if (
    l.includes(
      '"people.managementDesc": "Experienced leadership team overseeing 12,000 m' + M2 + ' facility, 200+ workers'
    )
  ) {
    mgmtIdxs.push(i);
  }
});
must(mgmtIdxs.length === 2, 'el+fi mgmt lines count, got ' + mgmtIdxs.length);
const mgmtIdx = mgmtIdxs.find((i) => uiLines[i + 5].includes('"people.subtitle": "Meet the team behind afarer'));
must(mgmtIdx !== undefined, 'fi anchor: no mgmt line followed by EN subtitle');
const fiMgmtSeq = uiLines.slice(mgmtIdx, mgmtIdx + 6).join('\n');
must(count(uiRaw, fiMgmtSeq) === 1, 'fi 6-line anchor count');
const fiMgmtRep =
  uiLines[mgmtIdx].match(/^\s*/)[0] +
  '"people.managementDesc": "Kokenut johtoryhm\u00E4 valvoo 12 000 m' +
  M2 +
  ':n tuotantolaitosta, 200+ ty\u00F6ntekij\u00E4\u00E4, toimitusketjua ja jatkuvan parantamisen ohjelmia.",\n' +
  uiLines.slice(mgmtIdx + 1, mgmtIdx + 6).join('\n');
ops.push({ f: uiPath, find: fiMgmtSeq, rep: fiMgmtRep });

// 4. da compare.inflatableVsHard Czech contamination -> REGISTERED as separate shard:
// 'nafukovac\u00ED' appears ~25x across the whole da UI block (systemic contamination,
// context-dependent Danish adjective forms needed) - NOT fixed here.

// safety: 39 #105 m2 op must stay satisfied post-patch (rep '12,000 m<sup>2' count >= 10)
const spaced = count(uiRaw, '12,000 m' + M2);
must(spaced >= 13, 'pre-patch 12,000 m2 count ' + spaced + ' (expect >=13; post-patch >=10)');

const out =
  '// shard 41 (GENERATED by _gen-ops-41.cjs \u2014 do not edit by hand)\n' +
  '// ' +
  ops.length +
  ' ops: da/fi SEP normalization (da comma->dot, fi comma->space; excl. 0,001 decimal + rgb/dataURI + 18 000 h site-uniform)\n' +
  '// UI dict: da/fi oem.why.factory.desc SEP, fi people.managementDesc EN->fi translation (6-line anchor)\n' +
  'module.exports = ' +
  JSON.stringify(ops, null, 2) +
  ';\n';
fs.writeFileSync(path.join(__dirname, '_ops-data-41.cjs'), out);
console.log('written: ' + ops.length + ' ops (yaml ' + yamlOps + ' + ui ' + (ops.length - yamlOps) + ')');
console.log('--- da spot ops ---');
ops
  .filter((o) => /\/da\//.test(o.f))
  .slice(0, 6)
  .forEach((o) => console.log('  ' + o.find.slice(0, 90) + '  =>  ' + o.rep.slice(0, 90)));
console.log('--- fi spot ops ---');
ops
  .filter((o) => /\/fi\//.test(o.f))
  .slice(0, 6)
  .forEach((o) => console.log('  ' + o.find.slice(0, 90) + '  =>  ' + o.rep.slice(0, 90)));
console.log('--- ui ops ---');
ops
  .filter((o) => o.f === uiPath)
  .forEach((o) => console.log('  [' + (o.n || 1) + '] ' + o.find.slice(0, 80) + '  =>  ' + o.rep.slice(0, 80)));
