// shard 40 GENERATOR: home proof_points retranslation, 20 locales
// EN SSOT = src/data/pages/home.yaml (Tested Beyond the Showroom; metrics 10+/50+/12-15/100%)
// Extracts exact old block (pre-patch state required) -> static ops module.
// Run from repo root: node TOOLS/i18n-merge/warning-cleanup/_gen-ops-40.cjs
const fs = require('fs');
const path = require('path');

const ROOT = 'E:/github/afarer';
const DATA = require('./_b40-data.cjs');
const LANGS = [
  'ar',
  'cs',
  'da',
  'de',
  'el',
  'es',
  'fi',
  'fr',
  'it',
  'ja',
  'ko',
  'nl',
  'no',
  'pl',
  'pt',
  'ro',
  'ru',
  'sv',
  'th',
  'tr',
];

const EN_DASH = '\u2013';
const ops = [];
let checked = 0;

function must(cond, msg) {
  if (!cond) {
    throw new Error('FAIL: ' + msg);
  }
}

for (const lang of LANGS) {
  const d = DATA[lang];
  must(d && d.t && d.s && Array.isArray(d.i) && d.i.length === 4, lang + ' data shape');
  const f = 'src/data/pages/' + lang + '/home.yaml';
  const txt = fs.readFileSync(path.join(ROOT, f), 'utf8');
  const lines = txt.split('\n');
  const si = lines.findIndex((l) => l === 'proof_points:');
  must(si >= 0, lang + ' proof_points line');
  let ei = si + 1;
  while (ei < lines.length && (lines[ei].startsWith('  ') || lines[ei].startsWith('\t'))) ei++;
  const blockLines = lines.slice(si, ei);
  must(blockLines.length === 16, lang + ' block 16 lines, got ' + blockLines.length);
  const find = blockLines.join('\n') + '\n';
  must(txt.split(find).length - 1 === 1, lang + ' find unique');
  must((find.match(/- metric:/g) || []).length === 4, lang + ' 4 metrics');
  must(/metric:\s*100\s*%/.test(find), lang + ' has 100%');
  must(!find.includes(EN_DASH), lang + ' old block must not contain en dash (pre-patch)');

  // YAML scalar safety
  const vals = [d.t, d.s, ...d.i.flat()];
  for (const v of vals) {
    must(v === v.trim() && !v.includes('\n'), lang + ' value shape: ' + JSON.stringify(v));
    must(!v.includes(': ') && !v.includes(' #') && !v.endsWith(':'), lang + ' yaml-unsafe: ' + JSON.stringify(v));
  }
  // apostrophe conventions
  if (lang === 'fr') {
    must(!d.t.includes("'") && !d.s.includes("'") && !d.i.flat().join('').includes("'"), 'fr straight apostrophe');
  } else if (lang === 'it' || lang === 'tr') {
    must(!vals.join('').includes('\u2019'), lang + ' unexpected U+2019');
  }

  const rep =
    'proof_points:\n' +
    '  title: ' +
    d.t +
    '\n' +
    '  subtitle: ' +
    d.s +
    '\n' +
    '  items:\n' +
    '    - metric: 10+\n' +
    '      label: ' +
    d.i[0][0] +
    '\n' +
    '      detail: ' +
    d.i[0][1] +
    '\n' +
    '    - metric: 50+\n' +
    '      label: ' +
    d.i[1][0] +
    '\n' +
    '      detail: ' +
    d.i[1][1] +
    '\n' +
    '    - metric: 12' +
    EN_DASH +
    '15\n' +
    '      label: ' +
    d.i[2][0] +
    '\n' +
    '      detail: ' +
    d.i[2][1] +
    '\n' +
    '    - metric: 100%\n' +
    '      label: ' +
    d.i[3][0] +
    '\n' +
    '      detail: ' +
    d.i[3][1] +
    '\n';

  must(rep !== find, lang + ' rep==find');
  must(rep.includes('metric: 12' + EN_DASH + '15'), lang + ' new metric');
  ops.push({ f, find, rep });
  checked++;
}

const out =
  '// shard 40 (GENERATED by _gen-ops-40.cjs from _b40-data.cjs \u2014 do not edit by hand)\n' +
  '// 20 ops: home proof_points retranslation x20 locales (EN SSOT: Tested Beyond the Showroom)\n' +
  '// metrics uniform 10+ / 50+ / 12\u201315 / 100%; fr apostrophes U+2019; it/tr straight\n' +
  'module.exports = ' +
  JSON.stringify(ops, null, 2) +
  ';\n';
fs.writeFileSync(path.join(__dirname, '_ops-data-40.cjs'), out);
console.log('written: ' + ops.length + ' ops, locales checked: ' + checked);
console.log('--- spot decode fr rep ---');
console.log(ops.find((o) => o.f.includes('/fr/')).rep);
console.log('--- spot decode th rep ---');
console.log(ops.find((o) => o.f.includes('/th/')).rep);
