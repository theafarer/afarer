const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.yaml'))
  .sort();
const unexpected = new Map();
for (const f of files) {
  const t = fs.readFileSync(path.join(dir, f), 'utf8');
  const toks = t.match(/[A-Za-zÀ-ÿ][A-Za-zÀ-ÿ'&.\-]*/g) || [];
  for (const tok of toks) {
    if (!allow.has(tok) && !allow.has(tok.replace(/'s$/, ''))) {
      const key = f + ' :: ' + tok;
      unexpected.set(key, (unexpected.get(key) || 0) + 1);
    }
  }
}
if (unexpected.size === 0) console.log('ALL LATIN TOKENS ALLOWLISTED');
else for (const [k, v] of [...unexpected.entries()].sort()) console.log(k, 'x' + v);
