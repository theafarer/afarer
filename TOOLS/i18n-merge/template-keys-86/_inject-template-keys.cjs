const locales = Object.keys(j);
let added = 0;
for (const [key, translations] of Object.entries(KEYS)) {
  for (const locale of locales) {
    const v = translations[locale];
    if (!v) {
      console.log('MISSING translation for ' + locale + ' / ' + key);
      process.exit(1);
    }
    if (j[locale][key] !== undefined && j[locale][key] !== v) {
      console.log('SKIP existing (differs): ' + locale + '/' + key + ' = ' + JSON.stringify(j[locale][key]));
      continue;
    }
    if (j[locale][key] === undefined) {
      j[locale][key] = v;
      added++;
    }
  }
}
fs.writeFileSync(FILE, JSON.stringify(j, null, 2) + '\n');
console.log('added ' + added + ' keys across ' + locales.length + ' locales');
