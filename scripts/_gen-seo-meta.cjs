const fs = require('fs');
const path = require('path');
const ROOT = process.cwd();
const GENERATED_DIR = path.join(ROOT, 'src/i18n/generated');
const PAGES_SRC = path.join(ROOT, 'src/pages/[lang]');

const pc = JSON.parse(fs.readFileSync(path.join(GENERATED_DIR, 'page-content.json'), 'utf8'));

// Build route path -> page key by scanning the [lang] routes.
// Also hardcode known mappings that can't be derived from getPageContent.
function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.astro')) out.push(p);
  }
  return out;
}

const routeFiles = walk(PAGES_SRC, []);

function routePathFor(file) {
  let rel = file
    .slice(PAGES_SRC.length)
    .replace(/\\/g, '/')
    .replace(/\.astro$/, '');
  if (rel.startsWith('/')) rel = rel.slice(1);
  if (rel.endsWith('/index')) rel = rel.slice(0, -'/index'.length);
  if (rel === 'index') rel = '';
  if (/\[.*\]/.test(rel)) return null;
  return '/' + rel;
}

const routeToPage = {};
for (const f of routeFiles) {
  const rp = routePathFor(f);
  if (!rp) continue;
  const c = fs.readFileSync(f, 'utf8');
  const m = c.match(/getPageContent\(lang,\s*'([^']+)'\)/);
  let page = m ? m[1] : null;
  if (!page && c.includes('import __pageData from')) {
    // fallback: home route uses getPageContent(lang) with default 'home'
    if (f.endsWith('index.astro') && path.dirname(f) === PAGES_SRC) page = 'home';
  }
  if (page) routeToPage[rp] = page;
}

// Additional manual mappings for routes whose pages aren't derivable:
const manual = {
  '/': 'home',
  '/about/afarer': 'about',
  '/brand': 'brand',
  '/brand/afarer': 'brand',
  '/brand/team': 'brand-team',
  '/compare': 'compare',
  '/use-cases': 'use-cases',
  '/solutions/by-industry': 'solutions',
  '/solutions/by-use-case': 'solutions',
  '/oem-odm-manufacturer': 'oem-odm-manufacturer',
  '/oem-process': 'oem-odm-manufacturer',
  '/oem-odm': 'oem-odm-manufacturer',
};
for (const [rp, page] of Object.entries(manual)) {
  if (!routeToPage[rp]) routeToPage[rp] = page;
}

// Now build the seo-meta map: lang + routePath -> {title, description, keywords}
const langs = [
  'en',
  'fr',
  'de',
  'pt',
  'es',
  'it',
  'ja',
  'ko',
  'ru',
  'pl',
  'ar',
  'nl',
  'sv',
  'no',
  'el',
  'tr',
  'fi',
  'cs',
  'da',
  'ro',
  'th',
  'zh',
];

const out = {};
for (const lang of langs) {
  for (const [rp, page] of Object.entries(routeToPage)) {
    const content = pc[`${lang}/${page}`];
    const meta = content && content.meta;
    if (meta && (meta.title || meta.description || meta.keywords)) {
      const entry = {};
      if (meta.title) entry.title = meta.title;
      if (meta.description) entry.description = meta.description;
      if (Array.isArray(meta.keywords)) entry.keywords = meta.keywords;
      else if (meta.keywords)
        entry.keywords = String(meta.keywords)
          .split(',')
          .map((s) => s.trim());
      out[`${lang}${rp}`] = entry;
    }
  }
}

const content =
  '// AUTO-GENERATED by scripts/_gen-seo-meta.cjs – do not edit.\n' +
  '// @ts-nocheck\n' +
  '// Small per-route meta (title/description/keywords) for localized SEO.\n' +
  'export const seoPageMeta = ' +
  JSON.stringify(out) +
  ';\n';

fs.mkdirSync(GENERATED_DIR, { recursive: true });
fs.writeFileSync(path.join(GENERATED_DIR, 'seo-meta.ts'), content);
console.log('wrote seo-meta.ts with', Object.keys(out).length, 'entries');
console.log('routes mapped:', Object.keys(routeToPage).length);
