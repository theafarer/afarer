// landing-i18n generator — reads src/data/landing-i18n/*.json and emits
// src/i18n/generated/landing/<name>.ts modules (export const landingI18n).
// Run from repo root: node scripts/_gen-landing-i18n.cjs
// Wired into package.json "build" and "generate" chains (after _gen-uiall.cjs).
// Data shape: { "<locale>": { "<EN key>": "<translation>", ... }, ... }
// Locales 'en' and 'fr' are intentionally absent: en is the key itself, fr lives in the source code.
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..');
const DATA_DIR = path.join(REPO, 'src', 'data', 'landing-i18n');
const OUT_DIR = path.join(REPO, 'src', 'i18n', 'generated', 'landing');

const VALID_LOCALES = new Set([
  'de',
  'pt',
  'es',
  'it',
  'ja',
  'ko',
  'ru',
  'pl',
  'ar',
  'nl',
  'sv',
  'no',
  'el',
  'tr',
  'fi',
  'cs',
  'da',
  'ro',
  'th',
]);

function tsEscape(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '');
}

if (!fs.existsSync(DATA_DIR)) {
  console.log('landing-i18n: no data dir, nothing to generate');
  process.exit(0);
}
const files = fs.readdirSync(DATA_DIR).filter((f) => f.endsWith('.json'));
if (files.length === 0) {
  console.log('landing-i18n: no data files, nothing to generate');
  process.exit(0);
}
fs.mkdirSync(OUT_DIR, { recursive: true });

let generated = 0;
for (const f of files) {
  const name = f.replace(/\.json$/, '');
  const raw = fs.readFileSync(path.join(DATA_DIR, f), 'utf8');
  let data;
  try {
    data = JSON.parse(raw);
  } catch (e) {
    console.error('landing-i18n: JSON parse failed for ' + f + ': ' + e.message);
    process.exit(1);
  }
  const localeLines = [];
  for (const locale of Object.keys(data)) {
    if (!VALID_LOCALES.has(locale)) {
      console.error('landing-i18n: unexpected locale "' + locale + '" in ' + f);
      process.exit(1);
    }
    const table = data[locale];
    if (typeof table !== 'object' || table === null || Array.isArray(table)) {
      console.error('landing-i18n: ' + f + ' locale "' + locale + '" is not an object');
      process.exit(1);
    }
    const lines = [];
    for (const k of Object.keys(table)) {
      const v = table[k];
      if (typeof v !== 'string') {
        console.error('landing-i18n: ' + f + ' [' + locale + '] key "' + k + '" has non-string value');
        process.exit(1);
      }
      lines.push("    '" + tsEscape(k) + "': '" + tsEscape(v) + "',");
    }
    localeLines.push('  ' + locale + ': {\n' + lines.join('\n') + '\n  },');
  }
  const out =
    '// AUTO-GENERATED by scripts/_gen-landing-i18n.cjs — do not edit.\n' +
    '// source: src/data/landing-i18n/' +
    f +
    '\n' +
    'export const landingI18n: Record<string, Record<string, string>> = {\n' +
    localeLines.join('\n') +
    '\n};\n';
  fs.writeFileSync(path.join(OUT_DIR, name + '.ts'), out, 'utf8');
  generated++;
}
console.log('landing-i18n: generated ' + generated + ' module(s) -> src/i18n/generated/landing/');
